import assert from "node:assert/strict";
import {chromium} from "playwright";

const browser=await chromium.launch({headless:true});
try{
  const page=await browser.newPage({viewport:{width:1600,height:950}});
  const errors=[];
  page.on("pageerror",error=>errors.push(error.message));
  await page.goto("http://127.0.0.1:8080",{waitUntil:"networkidle"});
  await page.evaluate(()=>{
    const seed=seedState();
    seed.setupComplete=true;
    seed.currentUserId="u_luis";
    localStorage.setItem("fluxosVisualState.prd4",JSON.stringify(seed));
    localStorage.removeItem("fluxosVisual.panes.prd41.u_luis");
  });
  await page.reload({waitUntil:"networkidle"});
  await page.locator(".prd41-workspace").waitFor();
  assert.equal(await page.locator(".prd41-pane").count(),3);
  assert.equal(await page.locator(".prd41-splitter").count(),2);
  assert.equal(await page.getByRole("tab",{name:/Sintética|Analítica|Gantt/}).count(),0);
  assert.equal(await page.locator("#prd4QuickCreate").count(),1,"unique quick create");
  assert.equal(await page.locator(".synth-table").count(),1);
  assert.equal(await page.locator("#graphCanvas svg").count(),1);
  assert.equal(await page.locator(".gantt-card").count(),1);
  const before=await page.locator(".prd41-pane--table").evaluate(el=>el.getBoundingClientRect().width);
  const splitter=page.locator('[data-pane-split="table-graph"]');
  const rect=await splitter.boundingBox();
  await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);
  await page.mouse.down();
  await page.mouse.move(rect.x+rect.width/2+90,rect.y+rect.height/2,{steps:6});
  await page.mouse.up();
  const after=await page.locator(".prd41-pane--table").evaluate(el=>el.getBoundingClientRect().width);
  assert.ok(after>before+55,"drag should grow table: "+before+" -> "+after);
  const layout=await page.evaluate(()=>JSON.parse(localStorage.getItem("fluxosVisual.panes.prd41.u_luis")));
  assert.ok(layout.table>34,"resized state persisted");
  await splitter.focus();
  await page.keyboard.press("ArrowLeft");
  const keyboard=await page.locator(".prd41-pane--table").evaluate(el=>el.getBoundingClientRect().width);
  assert.ok(keyboard<after-10,"keyboard resizing");
  await page.reload({waitUntil:"networkidle"});
  await page.locator(".prd41-workspace").waitFor();
  const restored=await page.locator(".prd41-pane--table").evaluate(el=>el.getBoundingClientRect().width);
  assert.ok(Math.abs(restored-keyboard)<5,"layout restored after reload");
  await page.locator('[data-pane-focus="graph"]').click();
  assert.equal(await page.locator(".prd41-workspace.is-focused").count(),1);
  assert.equal(await page.locator(".prd41-pane--table").isVisible(),false);
  assert.equal(await page.locator("#graphCanvas svg").isVisible(),true);
  await page.locator('[data-pane-focus="graph"]').click();
  assert.equal(await page.locator(".prd41-workspace.is-focused").count(),0);
  assert.equal(await page.locator(".prd41-pane--gantt").isVisible(),true);
  const itemId=await page.evaluate(()=>document.querySelector("[data-row]")?.dataset.row);
  assert.ok(itemId,"table should contain items");
  await page.locator('[data-row="'+itemId+'"] [data-select]').first().click();
  assert.equal(await page.locator('[data-row="'+itemId+'"].selected').count(),1);
  assert.equal(await page.locator('[data-gantt-row="'+itemId+'"].selected').count(),1);
  assert.equal(await page.locator('[data-node="'+itemId+'"]').count(),1);
  await page.keyboard.press("Escape");
  await page.locator("#showSubitemsGantt").check();
  assert.equal(await page.locator("#showSubitems").isChecked(),true);
  await page.locator("#prd4QuickCreate [name=title]").fill("Atividade PRD4.1");
  await page.locator("#prd4QuickCreate button[type=submit]").click();
  await page.getByText("1 item(ns) criado(s).").waitFor();
  assert.equal(await page.evaluate(()=>state.items.some(x=>x.title==="Atividade PRD4.1")),true);
  await page.locator('[data-pane-focus="graph"]').click();
  assert.ok(await page.locator(".graph-connector").count()>0);
  await page.locator('[data-action="propagate"]').click();
  await page.waitForTimeout(120);
  await page.locator('[data-action="pause-animation"]').click();
  await page.locator('[data-action="restart-animation"]').click();
  assert.deepEqual(errors,[],"No runtime browser errors");
  console.log("PRD4.1 smoke: 3 panes, drag/keyboard resize, persistence, focus, synced selection, creation, graph controls OK");
} finally {await browser.close();}
