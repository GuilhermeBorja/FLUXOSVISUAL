import assert from "node:assert/strict";
import { chromium } from "playwright";
import { fixture, createItem, ADMIN, TEST_PASSWORD } from "../tests/backend-support.mjs";

const cleanups = [];
const setup = await fixture({ after: callback => cleanups.push(callback) });
let browser;
try {
  const root = await createItem(setup.admin, "Arraste temporal", { type: "project" });
  await createItem(setup.admin, "Atividade deslocável", { parentId: root.id, plannedStartAt: "2026-11-02", plannedDurationDays: 5, baselineStartAt: "2026-11-02", baselineDueAt: "2026-11-06" });
  const before = await setup.admin.projection();
  const original = before.state.items.find(item => item.parentId === root.id);
  const originalTrend = before.trend?.itemTrendById?.[original.id] || null;
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  await page.goto(setup.baseUrl, { waitUntil: "networkidle" });
  await page.locator("#backendLoginForm [name=email]").fill(ADMIN.email);
  await page.locator("#backendLoginForm [name=password]").fill(TEST_PASSWORD);
  await page.locator("#backendLoginForm button[type=submit]").click();
  await page.waitForFunction(() => window.FluxosBackend?.status.ready);
  const expand = page.locator(`[data-gantt-row="${root.id}"] [data-expand]`);
  if ((await expand.getAttribute("aria-label"))?.startsWith("Expandir")) await expand.click();
  const bar = page.locator("[data-gantt-date-drag]").last();
  const initial = await bar.getAttribute("data-gantt-start");
  const box = await bar.boundingBox();
  assert.ok(box, "date drag bar exists");
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 600, box.y + box.height / 2, { steps: 8 });
  await page.mouse.up();
  await page.waitForTimeout(500);
  const shifted = await page.locator("[data-gantt-date-drag]").last().getAttribute("data-gantt-start");
  assert.notEqual(shifted, initial, "drag changes the visible trend draft");
  assert.equal(await page.locator('#commitmentProposalForm [name="startAt"]').inputValue(), shifted, "drag opens the proposal with the adjusted start date");
  await page.locator('.drawer [data-action="close-panel"]').click();
  const barAfterShift = page.locator("[data-gantt-date-drag]").last();
  const endHandle = barAfterShift.locator('[data-gantt-date-resize="end"]');
  const endBefore = await barAfterShift.getAttribute("data-gantt-end");
  const endBox = await endHandle.boundingBox();
  assert.ok(endBox, "end resize handle exists");
  await page.mouse.move(endBox.x + endBox.width / 2, endBox.y + endBox.height / 2);
  await page.mouse.down();
  await page.mouse.move(endBox.x + endBox.width / 2 + 180, endBox.y + endBox.height / 2, { steps: 6 });
  await page.mouse.up();
  await page.waitForTimeout(500);
  const endAfter = await page.locator("[data-gantt-date-drag]").last().getAttribute("data-gantt-end");
  assert.notEqual(endAfter, endBefore, "right edge changes the trend duration");
  assert.equal(await page.locator('#commitmentProposalForm [name="startAt"]').inputValue(), shifted, "resize keeps the adjusted start in the proposal");
  assert.equal(await page.locator('#commitmentProposalForm [name="dueAt"]').inputValue(), endAfter, "resize updates the proposal end date");
  await page.evaluate(() => window.FluxosBackend.flush());
  const afterGesture = await setup.admin.projection();
  const unchanged = afterGesture.state.items.find(item => item.id === original.id);
  assert.equal(unchanged.plannedStartAt, original.plannedStartAt, "gesture does not save the planned start");
  assert.equal(unchanged.plannedDurationDays, original.plannedDurationDays, "gesture does not save the planned duration");
  assert.equal(unchanged.baselineStartAt, original.baselineStartAt, "gesture does not change baseline start");
  assert.equal(unchanged.baselineDueAt, original.baselineDueAt, "gesture does not change baseline end");
  assert.deepEqual(afterGesture.trend?.itemTrendById?.[original.id] || null, originalTrend, "gesture does not save a new trend");
  assert.equal(afterGesture.commitments.filter(entry => entry.itemId === original.id && entry.kind === "agreement" && entry.status === "proposed").length, 0, "gesture does not send a proposal before form submission");
  await page.locator('#commitmentProposalForm button[type="submit"]').click();
  let afterProposal, proposal;
  for (let attempt = 0; attempt < 30 && !proposal; attempt++) {
    afterProposal = await setup.admin.projection();
    proposal = afterProposal.commitments.find(entry => entry.itemId === original.id && entry.kind === "agreement" && entry.status === "proposed");
    if (!proposal) await page.waitForTimeout(200);
  }
  assert.ok(proposal, "form submission sends a pending commitment proposal");
  assert.equal(proposal.startAt, shifted, "proposal uses the dragged start");
  assert.equal(proposal.dueAt, endAfter, "proposal uses the resized end");
  const afterSend = afterProposal.state.items.find(item => item.id === original.id);
  assert.equal(afterSend.plannedStartAt, original.plannedStartAt, "sending the proposal does not save the planned start");
  assert.equal(afterSend.plannedDurationDays, original.plannedDurationDays, "sending the proposal does not save the planned duration");
  assert.equal(afterSend.baselineStartAt, original.baselineStartAt, "sending the proposal does not change baseline start");
  assert.equal(afterSend.baselineDueAt, original.baselineDueAt, "sending the proposal does not change baseline end");
  await page.reload({ waitUntil: "networkidle" });
  await page.waitForFunction(() => window.FluxosBackend?.status.ready);
  const expandAfterReload = page.locator(`[data-gantt-row="${root.id}"] [data-expand]`);
  if ((await expandAfterReload.getAttribute("aria-label"))?.startsWith("Expandir")) await expandAfterReload.click();
  assert.equal(await page.locator("[data-gantt-date-drag]").last().getAttribute("data-gantt-start"), shifted, "pending proposal appears in the Gantt after reload");
  assert.equal(await page.locator("[data-gantt-date-drag]").last().getAttribute("data-gantt-end"), endAfter, "pending proposal end appears after reload");
  console.log("Gantt date drag: proposal submitted; baseline and plan unchanged.");
} finally {
  await browser?.close();
  for (const cleanup of cleanups.reverse()) await cleanup();
}
