import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { fixture, createItem, ADMIN, TEST_PASSWORD } from '../tests/backend-support.mjs';

const cleanups=[];
const setup=await fixture({after:callback=>cleanups.push(callback)});
let browser;
try {
  const root=await createItem(setup.admin,'Gantt interativo',{type:'project'});
  const first=await createItem(setup.admin,'Primeira atividade',{parentId:root.id});
  const second=await createItem(setup.admin,'Segunda atividade',{parentId:root.id});
  browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1600,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(setup.baseUrl,{waitUntil:'networkidle'});
  await page.locator('#backendLoginForm [name=email]').fill(ADMIN.email);
  await page.locator('#backendLoginForm [name=password]').fill(TEST_PASSWORD);
  await page.locator('#backendLoginForm button[type=submit]').click();
  await page.waitForFunction(()=>window.FluxosBackend?.status.ready);
  assert.equal(await page.locator('[data-status-date]').count(), 1, "workspace exposes the status date without opening a menu");
  assert.equal(await page.locator('[data-action="toggle-operations"]').count(), 1, "Meu painel control is visible");
  assert.equal(await page.locator("#operational-surfaces").count(), 0, "operational surfaces stay collapsed by default");
  await page.locator('[data-action="toggle-operations"]').click();
  assert.equal(await page.locator("#operational-surfaces").count(), 1, "Meu painel opens in a drawer");
  assert.match(await page.locator("#operational-surfaces").innerText(), /Data de status:/, "Meu painel exposes the status date");
  const drawerOrder=await page.locator("#operational-surfaces > section").evaluateAll(sections=>sections.map(section=>section.className));
  assert.ok(drawerOrder.indexOf("attention-group")>=0,"tendency section is visible");
  assert.ok(drawerOrder.indexOf("operational-horizon")>drawerOrder.findIndex(name=>name==="attention-group"),"horizon follows attention");
  assert.ok(drawerOrder.findIndex(name=>name.startsWith("my-actions"))>drawerOrder.indexOf("operational-horizon"),"my actions follow horizon");
  await page.locator('#operational-surfaces [data-action="toggle-operations"]').click();
  await page.locator('[data-action="toggle-operations"]').click();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator("#operational-surfaces").count(), 0, "Escape closes Meu painel");
  const expand=page.locator(`[data-gantt-row="${root.id}"] [data-expand]`);
  if((await expand.getAttribute('aria-label')).startsWith('Expandir'))await expand.click();
  assert.equal(await page.locator('[data-gantt-today]').count() > 0, true, 'Gantt exposes the current status date');
  const resize=page.locator('[data-gantt-resize="name"]');
  const heading=page.locator('[data-gantt-column="name"]');
  const before=(await heading.boundingBox()).width;
  const box=await resize.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();await page.mouse.move(box.x+box.width/2+80,box.y+box.height/2,{steps:8});await page.mouse.up();
  const after=(await heading.boundingBox()).width;
  assert.ok(after>before+50,`column grew from ${before} to ${after}`);
  await resize.focus();await page.keyboard.press('ArrowLeft');
  assert.ok((await heading.boundingBox()).width<after,'keyboard resizes column');
  await page.evaluate(()=>FluxosBackend.flushPreferences());
  await page.reload({waitUntil:'networkidle'});await page.waitForFunction(()=>window.FluxosBackend?.status.ready);
  assert.ok((await page.locator('[data-gantt-column="name"]').boundingBox()).width>before+35,'width persists after reload');
  const nameFilter=page.locator('[data-gantt-filter="name"]');
  await nameFilter.locator('xpath=../..').locator('summary').click();
  await nameFilter.fill('Primeira');await nameFilter.press('Tab');
  await page.waitForTimeout(50);
  assert.equal(await page.locator(`[data-gantt-row="${first.id}"]`).count(),1,'header filter keeps matching activity');
  assert.equal(await page.locator(`[data-gantt-row="${second.id}"]`).count(),0,'header filter hides non-matching activity');
  const clearNameFilter=page.locator('[data-gantt-filter="name"]');
  await clearNameFilter.locator('xpath=../..').locator('summary').click();
  await clearNameFilter.fill('');await clearNameFilter.press('Tab');
  const rootExpand=page.locator(`[data-gantt-row="${root.id}"] [data-expand]`);
  if((await rootExpand.getAttribute('aria-label')).startsWith('Expandir'))await rootExpand.click();
  const source=await page.locator(`[data-gantt-row-drag="${second.id}"]`).boundingBox();
  const target=await page.locator(`[data-gantt-row="${first.id}"]`).boundingBox();
  await page.mouse.move(source.x+source.width/2,source.y+source.height/2);await page.mouse.down();
  await page.mouse.move(target.x+40,target.y+3,{steps:12});
  assert.equal(await page.locator(`[data-gantt-row="${first.id}"].drop-before`).count(),1,'drop position shown');
  await page.mouse.up();await page.evaluate(()=>FluxosBackend.flush());
  const order=await page.locator('[data-gantt-row]').evaluateAll(rows=>rows.map(row=>row.dataset.ganttRow));
  assert.ok(order.indexOf(second.id)<order.indexOf(first.id),'task moved before sibling');
  await page.locator(`[data-gantt-row-drag="${second.id}"]`).focus();
  await page.keyboard.press('Alt+ArrowDown');await page.evaluate(()=>FluxosBackend.flush());
  const keyboardOrder=await page.locator('[data-gantt-row]').evaluateAll(rows=>rows.map(row=>row.dataset.ganttRow));
  assert.ok(keyboardOrder.indexOf(first.id)<keyboardOrder.indexOf(second.id),'keyboard moves task after sibling');
  for(const width of [1366,768,390]){
    await page.setViewportSize({width,height:900});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),`no page overflow at ${width}`);
    assert.ok(await page.locator('[data-gantt-resize="name"]').count(),'column handle remains available');
  }
  assert.deepEqual(errors,[]);
  console.log('Gantt interactions: pointer resize, keyboard resize, saved widths, pointer/keyboard row reorder and responsive containment passed.');
}finally{await browser?.close();for(const cleanup of cleanups.reverse())await cleanup();}
